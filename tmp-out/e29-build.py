def main():
    src = json.load(open(SRC))
    out = {"species": {}, "higher": {}}
    missing, badlen = [], []
    nfields = 0
    for latin, rec in src.items():
        fields = rec['fields_to_expand']
        entry = {}
        for f in fields:
            if latin not in E or f not in E[latin]:
                missing.append((latin, f)); continue
            text = E[latin][f]
            L = len(text)
            if f == 'morphology':
                lo, hi = (60, 110) if rec['noimg'] else (25, 45)
            else:
                lo, hi = (25, 50)
            if not (lo <= L <= hi):
                badlen.append((latin, f, L, lo, hi))
            entry[f] = text
            nfields += 1
        if entry:
            out['species'][latin] = entry
    if missing:
        print("MISSING:", missing); sys.exit(1)
    if badlen:
        print("BADLEN:")
        for b in badlen: print("  ", b)
        sys.exit(2)
    json.dump(out, open(OUT, 'w'), ensure_ascii=False, indent=2)
    print(f"OK: {len(out['species'])} species, {nfields} fields -> {OUT}")

if __name__ == '__main__':
    main()
